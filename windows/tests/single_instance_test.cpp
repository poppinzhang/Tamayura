#include "single_instance.h"

#include <cwchar>
#include <iostream>
#include <memory>
#include <stdexcept>
#include <string>
#include <vector>

namespace {

using SingleInstance = tamayura::SingleInstance;
using StartResult = SingleInstance::StartResult;

constexpr DWORD kPrimaryExit = 20;
constexpr DWORD kActivatedExit = 21;
constexpr DWORD kErrorExit = 22;
constexpr DWORD kTestTimeout = 10000;

void Require(bool value, const char* message) {
  if (!value) throw std::runtime_error(message);
}

class Handle {
 public:
  explicit Handle(HANDLE handle) : handle_(handle) {
    Require(handle_ != nullptr && handle_ != INVALID_HANDLE_VALUE,
            "native handle created");
  }
  ~Handle() { CloseHandle(handle_); }
  Handle(const Handle&) = delete;
  Handle& operator=(const Handle&) = delete;
  HANDLE get() const { return handle_; }

 private:
  HANDLE handle_;
};

void PumpMessages() {
  MSG message{};
  while (PeekMessageW(&message, nullptr, 0, 0, PM_REMOVE)) {
    TranslateMessage(&message);
    DispatchMessageW(&message);
  }
}

template <typename Predicate>
bool PumpUntil(Predicate finished, DWORD timeout_ms = kTestTimeout) {
  const ULONGLONG started = GetTickCount64();
  do {
    PumpMessages();
    if (finished()) return true;
    MsgWaitForMultipleObjects(0, nullptr, FALSE, 10, QS_ALLINPUT);
  } while (GetTickCount64() - started < timeout_ms);
  PumpMessages();
  return finished();
}

std::wstring Identity() {
  static unsigned int sequence = 0;
  return L"Tamayura.SingleInstance.Test." +
         std::to_wstring(GetCurrentProcessId()) + L"." +
         std::to_wstring(GetTickCount64()) + L"." + std::to_wstring(++sequence);
}

std::wstring EventName(const std::wstring& identity, const wchar_t* suffix) {
  return L"Local\\" + identity + suffix;
}

std::wstring ExecutablePath() {
  std::vector<wchar_t> buffer(32768);
  const DWORD size = GetModuleFileNameW(nullptr, buffer.data(),
                                        static_cast<DWORD>(buffer.size()));
  Require(size != 0 && size < buffer.size(), "test executable path resolved");
  return std::wstring(buffer.data(), size);
}

class Child {
 public:
  Child(const wchar_t* mode, const std::wstring& identity,
        const std::wstring& arguments = L"") {
    // Only the executable path needs quoting: identities and event names are
    // generated by this test and contain no spaces or shell metacharacters.
    const std::wstring executable = ExecutablePath();
    std::wstring command =
        L"\"" + executable + L"\" " + mode + L" " + identity + L" " + arguments;
    STARTUPINFOW startup{};
    startup.cb = sizeof(startup);
    PROCESS_INFORMATION process{};
    Require(CreateProcessW(executable.c_str(), command.data(), nullptr, nullptr,
                           FALSE, 0, nullptr, nullptr, &startup, &process) != 0,
            "test child process launched");
    process_ = process.hProcess;
    CloseHandle(process.hThread);
  }
  ~Child() {
    if (WaitForSingleObject(process_, 0) == WAIT_TIMEOUT) {
      TerminateProcess(process_, 99);
      WaitForSingleObject(process_, kTestTimeout);
    }
    CloseHandle(process_);
  }
  Child(const Child&) = delete;
  Child& operator=(const Child&) = delete;

  bool exited() const {
    return WaitForSingleObject(process_, 0) == WAIT_OBJECT_0;
  }

  DWORD exit_code() const {
    Require(exited(), "child has exited before inspecting its result");
    DWORD result = 0;
    Require(GetExitCodeProcess(process_, &result) != 0, "child result read");
    return result;
  }

  DWORD Wait() const {
    Require(PumpUntil([this] { return exited(); }), "test child completed");
    return exit_code();
  }

  DWORD WaitWithoutPumping() const {
    Require(WaitForSingleObject(process_, kTestTimeout) == WAIT_OBJECT_0,
            "test child completes while the primary does not service messages");
    return exit_code();
  }

  void Crash() const {
    Require(TerminateProcess(process_, 73) != 0,
            "terminate only the test-owned primary process");
    Require(Wait() == 73, "test primary terminated without cleanup");
  }

 private:
  HANDLE process_ = nullptr;
};

class TestWindow {
 public:
  TestWindow() {
    window_ = CreateWindowW(L"TamayuraSingleInstanceTest", L"Tamayura test",
                            WS_OVERLAPPEDWINDOW, CW_USEDEFAULT, CW_USEDEFAULT,
                            320, 200, nullptr, nullptr,
                            GetModuleHandleW(nullptr), nullptr);
    Require(window_ != nullptr, "test window created");
  }
  ~TestWindow() { DestroyWindow(window_); }
  TestWindow(const TestWindow&) = delete;
  TestWindow& operator=(const TestWindow&) = delete;
  HWND get() const { return window_; }

 private:
  HWND window_ = nullptr;
};

DWORD Probe(const std::wstring& identity, DWORD timeout_ms = 3000) {
  Child child(L"--probe", identity, std::to_wstring(timeout_ms));
  return child.Wait();
}

DWORD ExitCode(StartResult result) {
  switch (result) {
    case StartResult::kPrimary:
      return kPrimaryExit;
    case StartResult::kActivated:
      return kActivatedExit;
    case StartResult::kError:
      return kErrorExit;
  }
  return 1;
}

int RunChild(int argc, wchar_t** argv) {
  Require(argc == 4 || argc == 5, "valid test child arguments");
  const std::wstring mode = argv[1];
  const std::wstring identity = argv[2];
  if (mode == L"--probe") {
    Require(argc == 4, "probe arguments");
    SingleInstance instance(identity);
    const auto timeout = static_cast<DWORD>(std::wcstoul(argv[3], nullptr, 10));
    return static_cast<int>(ExitCode(instance.Start(timeout)));
  }

  Require(argc == 5 && (mode == L"--race" || mode == L"--owner"),
          "owner arguments");
  Handle ready_or_gate(
      OpenEventW(SYNCHRONIZE | EVENT_MODIFY_STATE, FALSE, argv[3]));
  Handle release(OpenEventW(SYNCHRONIZE, FALSE, argv[4]));
  if (mode == L"--race") {
    Require(
        WaitForSingleObject(ready_or_gate.get(), kTestTimeout) == WAIT_OBJECT_0,
        "concurrent launch gate opened");
  }
  SingleInstance instance(identity);
  const StartResult result = instance.Start(3000);
  if (result != StartResult::kPrimary) {
    return static_cast<int>(ExitCode(result));
  }
  if (mode == L"--owner") {
    Require(SetEvent(ready_or_gate.get()) != 0, "primary readiness signaled");
  }
  // A primary stays alive and services its activation endpoint until the
  // parent releases it, so a second primary cannot be hidden by a quick exit.
  Require(PumpUntil([&release] {
            return WaitForSingleObject(release.get(), 0) == WAIT_OBJECT_0;
          }),
          "primary released by parent");
  return static_cast<int>(kPrimaryExit);
}

void TestRepeatLaunchAndWindowStates() {
  const auto identity = Identity();
  SingleInstance instance(identity);
  Require(instance.Start() == StartResult::kPrimary, "first launch is primary");
  TestWindow window;
  instance.SetWindow(window.get());
  Require(!IsWindowVisible(window.get()), "binding alone does not show window");

  Require(Probe(identity) == kActivatedExit, "second launch only activates");
  Require(IsWindowVisible(window.get()) && !IsIconic(window.get()),
          "repeat launch reveals the hidden tray window");
  Require(Probe(identity) == kActivatedExit && IsWindowVisible(window.get()),
          "repeat launch keeps the existing visible window");

  ShowWindow(window.get(), SW_MINIMIZE);
  Require(IsIconic(window.get()), "window minimized before activation");
  Require(Probe(identity) == kActivatedExit && !IsIconic(window.get()) &&
              IsWindowVisible(window.get()),
          "repeat launch restores a minimized window");

  ShowWindow(window.get(), SW_MAXIMIZE);
  ShowWindow(window.get(), SW_HIDE);
  Require(Probe(identity) == kActivatedExit && IsZoomed(window.get()) &&
              IsWindowVisible(window.get()),
          "repeat launch preserves hidden maximized window state");
  ShowWindow(window.get(), SW_MINIMIZE);
  Require(Probe(identity) == kActivatedExit && !IsIconic(window.get()) &&
              IsZoomed(window.get()),
          "restoring a minimized maximized window preserves maximization");
  // Foreground ownership is intentionally not asserted: Windows can deny
  // focus and CI runners may have a noninteractive desktop.
}

void TestEarlyActivation() {
  const auto identity = Identity();
  SingleInstance instance(identity);
  Require(instance.Start() == StartResult::kPrimary, "early primary started");
  TestWindow window;
  Require(Probe(identity) == kActivatedExit, "early activation acknowledged");
  Require(!IsWindowVisible(window.get()), "unbound window stays hidden");
  instance.SetWindow(window.get());
  Require(IsWindowVisible(window.get()),
          "first frame consumes pending request");
  ShowWindow(window.get(), SW_HIDE);
  instance.SetWindow(window.get());
  Require(!IsWindowVisible(window.get()), "pending activation consumed once");
}

void TestConcurrentColdLaunches() {
  const auto identity = Identity();
  const auto gate_name = EventName(identity, L".gate");
  const auto release_name = EventName(identity, L".release");
  Handle gate(CreateEventW(nullptr, TRUE, FALSE, gate_name.c_str()));
  Handle release(CreateEventW(nullptr, TRUE, FALSE, release_name.c_str()));
  std::vector<std::unique_ptr<Child>> children;
  for (int index = 0; index < 6; ++index) {
    children.push_back(std::make_unique<Child>(
        L"--race", identity, gate_name + L" " + release_name));
  }
  Require(SetEvent(gate.get()) != 0, "concurrent launches released together");
  Require(PumpUntil([&children] {
            size_t exited = 0;
            for (const auto& child : children) {
              if (child->exited()) {
                Require(child->exit_code() == kActivatedExit,
                        "losing concurrent launch activates the primary");
                ++exited;
              }
            }
            return exited == children.size() - 1;
          }),
          "exactly one concurrent primary remains running");
  Require(SetEvent(release.get()) != 0, "concurrent primary released");
  int primaries = 0;
  for (const auto& child : children) {
    const DWORD result = child->Wait();
    Require(result == kPrimaryExit || result == kActivatedExit,
            "concurrent launch has a valid result");
    if (result == kPrimaryExit) ++primaries;
  }
  Require(primaries == 1,
          "concurrent cold launches create exactly one primary");
}

void TestRestartAfterExit() {
  const auto identity = Identity();
  {
    SingleInstance instance(identity);
    Require(instance.Start() == StartResult::kPrimary,
            "restart primary started");
    Require(Probe(identity) == kActivatedExit,
            "live owner excludes new primary");
  }
  Require(Probe(identity) == kPrimaryExit,
          "normal exit releases endpoint and ownership for a fresh process");
}

void TestAbandonedOwnerRecovery() {
  const auto identity = Identity();
  const auto ready_name = EventName(identity, L".ready");
  const auto release_name = EventName(identity, L".release");
  Handle ready(CreateEventW(nullptr, TRUE, FALSE, ready_name.c_str()));
  Handle release(CreateEventW(nullptr, TRUE, FALSE, release_name.c_str()));
  Child owner(L"--owner", identity, ready_name + L" " + release_name);
  Require(PumpUntil([&ready] {
            return WaitForSingleObject(ready.get(), 0) == WAIT_OBJECT_0;
          }),
          "crash-test primary owns its mutex and endpoint");
  // Keep a second handle alive so terminating the owner leaves an abandoned
  // mutex, rather than deleting the named object and creating a fresh mutex.
  Handle retained(OpenMutexW(SYNCHRONIZE | MUTEX_MODIFY_STATE, FALSE,
                             (L"Local\\" + identity).c_str()));
  owner.Crash();
  SingleInstance replacement(identity);
  Require(replacement.Start(3000) == StartResult::kPrimary,
          "abandoned ownership is reclaimed after a crashed process");
  Require(Probe(identity) == kActivatedExit,
          "replacement endpoint handles subsequent launches");
}

void TestMissingEndpointFailsClosed() {
  const auto identity = Identity();
  Handle owner(CreateMutexW(nullptr, TRUE, (L"Local\\" + identity).c_str()));
  Require(Probe(identity, 200) == kErrorExit,
          "a held mutex without an endpoint never starts another primary");
  Require(ReleaseMutex(owner.get()) != 0, "simulated stalled owner releases");
  Require(Probe(identity) == kPrimaryExit,
          "launch succeeds after the stalled owner releases ownership");
}

void TestKernelObjectNameCollision() {
  const auto identity = Identity();
  {
    // Events and mutexes share the kernel object namespace. A different
    // object type with the same name makes CreateMutexExW fail for real.
    Handle conflicting_event(
        CreateEventW(nullptr, TRUE, FALSE, (L"Local\\" + identity).c_str()));
    Require(Probe(identity) == kErrorExit,
            "mutex creation failure refuses an unprotected primary");
  }
  Require(Probe(identity) == kPrimaryExit,
          "a failed start leaves no ownership after conflict removal");
}

void TestUnresponsiveEndpointFailsClosed() {
  const auto identity = Identity();
  SingleInstance instance(identity);
  Require(instance.Start() == StartResult::kPrimary,
          "unresponsive-test primary owns its mutex and endpoint");
  Child child(L"--probe", identity, L"200");
  Require(child.WaitWithoutPumping() == kErrorExit,
          "an existing unresponsive endpoint never permits a second primary");
  // A timed-out activation can still be dispatched later. Resume servicing
  // messages and verify ownership without asserting on delayed window state.
  PumpMessages();
  Require(Probe(identity) == kActivatedExit,
          "the same primary handles launches once its UI thread responds");
}

void TestStopActivation() {
  const auto identity = Identity();
  TestWindow window;
  {
    SingleInstance instance(identity);
    Require(instance.Start() == StartResult::kPrimary,
            "stopping primary started");
    Require(Probe(identity) == kActivatedExit, "pending request before stop");
    instance.StopActivation();
    instance.SetWindow(window.get());
    Require(!IsWindowVisible(window.get()),
            "stopping discards pending request");
    Require(Probe(identity, 200) == kErrorExit,
            "stopping primary retains ownership and refuses activation");
    Require(!IsWindowVisible(window.get()),
            "stopping never revives old window");
  }
  Require(Probe(identity) == kPrimaryExit,
          "new primary may start after stopped instance finishes cleanup");
  Require(!IsWindowVisible(window.get()),
          "new process never revives old window");
}

}  // namespace

int wmain(int argc, wchar_t** argv) {
  try {
    if (argc > 1) return RunChild(argc, argv);
    WNDCLASSW window_class{};
    window_class.lpfnWndProc = DefWindowProcW;
    window_class.hInstance = GetModuleHandleW(nullptr);
    window_class.lpszClassName = L"TamayuraSingleInstanceTest";
    Require(RegisterClassW(&window_class) != 0, "test window class registered");
    TestRepeatLaunchAndWindowStates();
    TestEarlyActivation();
    TestConcurrentColdLaunches();
    TestRestartAfterExit();
    TestAbandonedOwnerRecovery();
    TestMissingEndpointFailsClosed();
    TestKernelObjectNameCollision();
    TestUnresponsiveEndpointFailsClosed();
    TestStopActivation();
    std::cout << "Single instance tests passed\n";
    return 0;
  } catch (const std::exception& error) {
    std::cerr << error.what() << '\n';
    return 1;
  }
}
